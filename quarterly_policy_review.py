"""Quarterly policy review bot.

Reads data/policies.json, lists overdue (> 365 days) and due-soon (> 305 days)
policies, and posts ONE report per quarter. Re-running in the same quarter
edits that quarter's issue instead of opening a duplicate (idempotent).

    python3 quarterly_policy_review.py          # print the report
    python3 quarterly_policy_review.py --post   # create/update the GitHub issue
"""
from __future__ import annotations

import datetime as dt
import json
import subprocess
import sys
from pathlib import Path

DATA = Path(__file__).parent / "data"


def report() -> tuple[str, str]:
    rows = json.loads((DATA / "policies.json").read_text())["rows"]
    today = dt.date.today()
    q = (today.month - 1) // 3 + 1
    title = f"Policy review status — {today.year} Q{q}"
    over = sorted([r for r in rows if r["status"] == "Overdue"], key=lambda r: -r["age_days"])
    soon = sorted([r for r in rows if r["status"] == "Due < 60 days"], key=lambda r: -r["age_days"])
    lines = [f"**{len(rows) - len(over) - len(soon)} current · {len(soon)} due within 60 days · {len(over)} overdue** (sample data, Northwind Cloud is fictional)", ""]
    for label, items in (("Overdue", over), ("Due within 60 days", soon)):
        if items:
            lines += [f"### {label}", "| Policy | Last review | Age (days) | Owner |", "|---|---|---|---|"]
            lines += [f"| {r['policy']} | {r['last_review']} | {r['age_days']} | {r['owner_team']} |" for r in items]
            lines.append("")
    lines.append("_Generated by `quarterly_policy_review.py` from the register. Re-runs update this issue._")
    return title, "\n".join(lines)


def main():
    title, body = report()
    if "--post" not in sys.argv:
        print(f"# {title}\n\n{body}")
        return
    existing = json.loads(subprocess.run(["gh", "issue", "list", "--state", "all", "--search", f'"{title}" in:title',
                                          "--json", "number,title"], capture_output=True, text=True, check=True).stdout)
    match = next((i["number"] for i in existing if i["title"] == title), None)
    if match:
        subprocess.run(["gh", "issue", "edit", str(match), "--body", body], check=True)
        print(f"updated #{match}")
    else:
        subprocess.run(["gh", "issue", "create", "--title", title, "--body", body], check=True)


if __name__ == "__main__":
    main()
